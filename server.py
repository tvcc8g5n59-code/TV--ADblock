#!/usr/bin/env python3
"""TV Blocker: control panel for a dnsmasq DNS sinkhole.

Standard library only, so the container needs no pip installs.
dnsmasq answers lookups for blocked domains with 0.0.0.0, so the TV's
tracking/ACR connections fail before they reach the internet.
"""
import base64
import hmac
import json
import os
import re
import signal
import subprocess
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.environ.get("DATA_DIR", "/data")
PORT = int(os.environ.get("GUI_PORT", "8080"))
GUI_PASSWORD = os.environ.get("GUI_PASSWORD", "")
UPSTREAM = [u.strip() for u in os.environ.get("UPSTREAM_DNS", "1.1.1.1,9.9.9.9").split(",") if u.strip()]
DEFAULTS = os.environ.get("DEFAULTS_FILE", "/opt/tv-blocker/defaults/tv-domains.txt")
INDEX = os.path.join(HERE, "index.html")

STATE = os.path.join(DATA, "state.json")
CUSTOM = os.path.join(DATA, "custom-domains.txt")
ALLOW = os.path.join(DATA, "allow-domains.txt")
CONF = os.path.join(DATA, "dnsmasq.conf")
PIDFILE = os.path.join(DATA, "dnsmasq.pid")
QLOG = os.path.join(DATA, "dnsmasq.log")

DOMAIN_RE = re.compile(r"^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")
HIT_RE = re.compile(r"config (\S+) is (?:0\.0\.0\.0|::)")
# dnsmasq logs every query as: "query[A] example.com from 192.168.1.50"
QUERY_RE = re.compile(r"query\[\w+\] (\S+) from (\S+)")
# Words that suggest telemetry, tracking or ads. This is a hint, not a verdict.
SUSPECT_WORDS = ("telemetry", "track", "analytic", "metric", "collect", "log", "logs",
                 "ads", "adserv", "pixel", "beacon", "sdk", "stat", "insight", "measure")
# Subdomain labels that usually mean tracking when they lead a name.
STRONG_LABELS = {"telemetry", "metrics", "analytics", "track", "tracking", "pixel",
                 "ads", "ad", "stats", "collect", "beacon", "insights"}
# Ad and tracking domains from uBlock Origin's filter lists, bundled with the app.
KNOWN_FILE = os.path.join(os.path.dirname(DEFAULTS), "ublock-domains.txt")
FLAG_SCORE = 6  # domains at or above this score are "flagged"

lock = threading.Lock()
last_error = ""


# ---------- domain lists ----------

def normalize(raw):
    d = raw.strip().lower().rstrip(".")
    d = re.sub(r"^https?://", "", d).split("/")[0]
    if d.startswith("*."):
        d = d[2:]
    return d


def valid(d):
    return bool(DOMAIN_RE.match(d))


def read_list(path):
    out = []
    if not os.path.exists(path):
        return out
    with open(path) as f:
        for line in f:
            item = line.split("#", 1)[0].strip().lower()
            if item and valid(item):
                out.append(item)
    return out


def write_list(path, items):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(sorted(set(items))) + "\n")
    os.replace(tmp, path)


def load_state():
    try:
        with open(STATE) as f:
            return json.load(f)
    except (OSError, ValueError):
        return {"enabled": True}


def save_state(st):
    tmp = STATE + ".tmp"
    with open(tmp, "w") as f:
        json.dump(st, f)
    os.replace(tmp, STATE)


def effective():
    """Return (state, blocked domains, allowed domains)."""
    st = load_state()
    allow = set(read_list(ALLOW))
    blocked = (set(read_list(DEFAULTS)) | set(read_list(CUSTOM))) - allow
    return st, sorted(blocked), sorted(allow)


# ---------- dnsmasq ----------

def write_conf(st, blocked, allow):
    lines = [
        "# generated by TV Blocker; edits here are overwritten",
        "port=53",
        "no-resolv",
        "domain-needed",
        "bogus-priv",
        "cache-size=2000",
        "log-queries",
        "log-facility=" + QLOG,
    ]
    lines += ["server=" + u for u in UPSTREAM]
    # Allowed domains are forwarded upstream. dnsmasq prefers the most
    # specific match, so this also lets an allowed subdomain of a blocked
    # parent resolve.
    lines += ["server=/%s/%s" % (d, UPSTREAM[0]) for d in allow]
    if st.get("enabled", True):
        for d in blocked:
            lines.append("address=/%s/0.0.0.0" % d)
            lines.append("address=/%s/::" % d)
    tmp = CONF + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, CONF)


def dnsmasq_pid():
    try:
        with open(PIDFILE) as f:
            pid = int(f.read().strip())
        os.kill(pid, 0)
        return pid
    except (OSError, ValueError):
        return None


def stop_dnsmasq():
    pid = dnsmasq_pid()
    if not pid:
        return
    try:
        os.kill(pid, signal.SIGTERM)
    except OSError:
        return
    for _ in range(30):
        if dnsmasq_pid() is None:
            return
        time.sleep(0.1)
    try:
        os.kill(pid, signal.SIGKILL)
    except OSError:
        pass


def start_dnsmasq():
    r = subprocess.run(["dnsmasq", "--test", "--conf-file=" + CONF],
                       capture_output=True, text=True)
    if r.returncode != 0:
        return (r.stderr or r.stdout).strip() or "config check failed"
    r = subprocess.run(["dnsmasq", "--conf-file=" + CONF, "--pid-file=" + PIDFILE],
                       capture_output=True, text=True)
    if r.returncode != 0:
        return (r.stderr or r.stdout).strip() or "dnsmasq failed to start"
    for _ in range(20):
        if dnsmasq_pid():
            return ""
        time.sleep(0.1)
    return "dnsmasq did not stay running (is port 53 already in use?)"


def apply():
    """Rebuild the config and restart dnsmasq. Returns an error string or ''."""
    global last_error
    st, blocked, allow = effective()
    write_conf(st, blocked, allow)
    stop_dnsmasq()
    last_error = start_dnsmasq()
    return last_error


def read_log_tail(max_bytes=4_000_000):
    """Recent part of the dnsmasq query log as text."""
    if not os.path.exists(QLOG):
        return ""
    size = os.path.getsize(QLOG)
    with open(QLOG, "rb") as f:
        f.seek(max(0, size - max_bytes))
        return f.read().decode("utf-8", "replace")


def read_hits(limit=25):
    """Top blocked domains from the recent part of the dnsmasq query log."""
    counts = {}
    for m in HIT_RE.finditer(read_log_tail()):
        counts[m.group(1)] = counts.get(m.group(1), 0) + 1
    top = sorted(counts.items(), key=lambda kv: -kv[1])[:limit]
    return [{"domain": d, "count": c} for d, c in top]


def is_blocked(domain, blocked_set):
    """True if the domain or any parent domain is on the blocklist."""
    parts = domain.split(".")
    return any(".".join(parts[i:]) in blocked_set for i in range(len(parts)))


def has_word(token, word):
    """Whole-token match for short words ("log" is not "logistics"); prefix
    match for longer ones ("analytic" matches "analytics")."""
    if token == word:
        return True
    return len(word) >= 6 and token.startswith(word)


def score_domain(name, count, known_set):
    """Score 1 (benign-looking) to 10 (very likely ad or tracking).

    A heuristic built from signals we can see without outside services:
    membership in the bundled ad/tracker list, keywords and telemetry-style
    subdomain labels, and how often the device asks for it. It is a guess,
    not a reputation lookup, so check high scores before blocking.
    """
    score = 1
    reasons = []

    if is_blocked(name, known_set):
        score += 5
        reasons.append("on a known ad/tracker list")

    labels = name.split(".")
    tokens = [t for t in re.split(r"[.\-_]", name) if t]
    words = [w for w in SUSPECT_WORDS if any(has_word(t, w) for t in tokens)]
    if words:
        score += min(3, 2 * len(words))
        reasons.append("name contains: " + ", ".join(words))

    # Only labels before the registered domain count, e.g. "metrics" in metrics.example.com.
    if any(label in STRONG_LABELS for label in labels[:-2]):
        score += 1
        reasons.append("subdomain looks like tracking")

    if count >= 50:
        score += 1
        reasons.append("queried very often (%d)" % count)

    return min(10, score), reasons


def read_traffic(device=None, limit=100):
    """Domains queried by devices on the network that are not already blocked.

    Returns the devices seen (by IP) and, for the chosen device (or all
    devices), the domains it asked for, most frequent first, each with a
    1-10 score for how likely it is ad or tracking traffic.
    """
    _, blocked, allow = effective()
    blocked_set = set(blocked)
    allow_set = set(allow)
    known_set = set(read_list(KNOWN_FILE))

    devices, domains = {}, {}
    for m in QUERY_RE.finditer(read_log_tail()):
        name, ip = m.group(1).lower(), m.group(2)
        devices[ip] = devices.get(ip, 0) + 1
        if device and ip != device:
            continue
        domains[name] = domains.get(name, 0) + 1

    rows = []
    for name, count in sorted(domains.items(), key=lambda kv: -kv[1]):
        if name in allow_set or is_blocked(name, blocked_set):
            continue
        score, reasons = score_domain(name, count, known_set)
        rows.append({
            "domain": name,
            "count": count,
            "score": score,
            "reasons": reasons,
            "flagged": score >= FLAG_SCORE,
        })
        if len(rows) >= limit:
            break
    rows.sort(key=lambda r: (-r["score"], -r["count"]))

    return {
        "devices": [{"ip": ip, "count": c}
                    for ip, c in sorted(devices.items(), key=lambda kv: -kv[1])],
        "domains": rows,
    }


def status():
    st, blocked, allow = effective()
    enabled = st.get("enabled", True)
    return {
        "enabled": enabled,
        "running": dnsmasq_pid() is not None,
        "error": last_error,
        "blocked_total": len(blocked) if enabled else 0,
        "default_count": len(read_list(DEFAULTS)),
        "custom": read_list(CUSTOM),
        "allow": allow,
        "upstream": UPSTREAM,
        "hits": read_hits(),
    }


# ---------- HTTP ----------

def handle_post(path, body):
    with lock:
        if path == "/api/toggle":
            st = load_state()
            st["enabled"] = bool(body.get("enabled"))
            save_state(st)
            return 200, {"ok": True, "error": apply()}

        if path == "/api/domains":
            target = {"custom": CUSTOM, "allow": ALLOW}.get(body.get("list"))
            action = body.get("action")
            if not target or action not in ("add", "remove"):
                return 400, {"error": "bad request"}
            domain = normalize(str(body.get("domain", "")))
            if not valid(domain):
                return 400, {"error": "that is not a valid domain name"}
            items = set(read_list(target))
            if action == "add":
                items.add(domain)
            else:
                items.discard(domain)
            write_list(target, items)
            return 200, {"ok": True, "error": apply()}

    return 404, {"error": "not found"}


class Handler(BaseHTTPRequestHandler):
    server_version = "TVBlocker"

    def log_message(self, fmt, *args):
        pass

    def _authorized(self):
        if not GUI_PASSWORD:
            return True
        hdr = self.headers.get("Authorization", "")
        if not hdr.startswith("Basic "):
            return False
        try:
            _, _, pw = base64.b64decode(hdr[6:]).decode("utf-8", "replace").partition(":")
        except ValueError:
            return False
        return hmac.compare_digest(pw.encode(), GUI_PASSWORD.encode())

    def _reply(self, code, body, ctype="application/json", headers=None):
        if isinstance(body, (dict, list)):
            body = json.dumps(body).encode()
        elif isinstance(body, str):
            body = body.encode()
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        for k, v in (headers or {}).items():
            self.send_header(k, v)
        self.end_headers()
        self.wfile.write(body)

    def _deny(self):
        self._reply(401, {"error": "login required"},
                    headers={"WWW-Authenticate": 'Basic realm="TV Blocker"'})

    def do_GET(self):
        path = urlparse(self.path).path
        if path == "/healthz":
            return self._reply(200, "ok", "text/plain")
        if not self._authorized():
            return self._deny()
        if path in ("/", "/index.html"):
            with open(INDEX, "rb") as f:
                return self._reply(200, f.read(), "text/html; charset=utf-8")
        if path == "/api/status":
            return self._reply(200, status())
        if path == "/api/traffic":
            query = parse_qs(urlparse(self.path).query)
            device = (query.get("device") or [""])[0].strip() or None
            return self._reply(200, read_traffic(device))
        self._reply(404, {"error": "not found"})

    def do_POST(self):
        if not self._authorized():
            return self._deny()
        length = int(self.headers.get("Content-Length") or 0)
        if length > 16_384:
            return self._reply(413, {"error": "request too large"})
        try:
            body = json.loads(self.rfile.read(length) or b"{}")
        except ValueError:
            return self._reply(400, {"error": "invalid JSON"})
        if not isinstance(body, dict):
            return self._reply(400, {"error": "expected a JSON object"})
        code, out = handle_post(urlparse(self.path).path, body)
        self._reply(code, out)


def main():
    os.makedirs(DATA, exist_ok=True)
    for p in (CUSTOM, ALLOW):
        open(p, "a").close()
    if not os.path.exists(STATE):
        save_state({"enabled": True})

    err = apply()
    print("dnsmasq:", "running" if not err else "ERROR: " + err, flush=True)

    def shutdown(*_):
        stop_dnsmasq()
        sys.exit(0)

    signal.signal(signal.SIGTERM, shutdown)
    signal.signal(signal.SIGINT, shutdown)

    srv = ThreadingHTTPServer(("0.0.0.0", PORT), Handler)
    print("TV Blocker GUI on port %d" % PORT, flush=True)
    srv.serve_forever()


if __name__ == "__main__":
    main()
